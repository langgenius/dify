#!/bin/bash

tail -F /var/log/squid/access.log 2>/dev/null &
tail -F /var/log/squid/error.log 2>/dev/null &
tail -F /var/log/squid/store.log 2>/dev/null &
tail -F /var/log/squid/cache.log 2>/dev/null &

SANDBOX_PROXY_CONF=/etc/squid/dify_sandbox_proxy.conf

{
    echo "# Generated by docker-agent-entrypoint.sh."
    echo "# Exposes shellctl through the proxy container when configured."
} > "$SANDBOX_PROXY_CONF"

if [ -n "${SSRF_SANDBOX_PROXY_PORT:-}" ]; then
    sandbox_proxy_host="${SSRF_SANDBOX_PROXY_HOST:-local_sandbox}"
    sandbox_proxy_target_port="${SANDBOX_PORT:-5004}"

    {
        printf 'http_port %s accel vhost\n' "$SSRF_SANDBOX_PROXY_PORT"
        printf 'acl dify_agent_sandbox_proxy_port localport %s\n' "$SSRF_SANDBOX_PROXY_PORT"
        printf 'cache_peer %s parent %s 0 no-query no-digest originserver name=dify_agent_sandbox\n' \
            "$sandbox_proxy_host" \
            "$sandbox_proxy_target_port"
        printf 'cache_peer_access dify_agent_sandbox allow dify_agent_sandbox_proxy_port\n'
        printf 'cache_peer_access dify_agent_sandbox deny all\n'
        printf 'http_access allow dify_agent_sandbox_proxy_port\n'
    } >> "$SANDBOX_PROXY_CONF"
fi

resolve_ipv4() {
    getent ahostsv4 "$1" | awk 'NR == 1 { print $1 }'
}

if [ -n "${SSRF_AGENT_BACKEND_UPSTREAM_HOST:-}" ]; then
    agent_backend_upstream="$(resolve_ipv4 "$SSRF_AGENT_BACKEND_UPSTREAM_HOST")"
    if [ -z "$agent_backend_upstream" ]; then
        echo "Unable to resolve Agent backend upstream: $SSRF_AGENT_BACKEND_UPSTREAM_HOST" >&2
        exit 1
    fi
    {
        printf 'cache_peer %s parent %s 0 no-query no-digest originserver login=PASS name=dify_agent_backend\n' \
            "$agent_backend_upstream" \
            "${SSRF_AGENT_BACKEND_UPSTREAM_PORT:-5050}"
        printf 'cache_peer_access dify_agent_backend allow dst_agent_backend path_agent_stub\n'
        printf 'cache_peer_access dify_agent_backend deny all\n'
        printf 'never_direct allow dst_agent_backend path_agent_stub\n'
    } >> "$SANDBOX_PROXY_CONF"
fi

if [ -n "${SSRF_API_UPSTREAM_HOST:-}" ]; then
    api_upstream="$(resolve_ipv4 "$SSRF_API_UPSTREAM_HOST")"
    if [ -z "$api_upstream" ]; then
        echo "Unable to resolve API upstream: $SSRF_API_UPSTREAM_HOST" >&2
        exit 1
    fi
    {
        printf 'cache_peer %s parent %s 0 no-query no-digest originserver name=dify_api\n' \
            "$api_upstream" \
            "${SSRF_API_UPSTREAM_PORT:-5001}"
        printf 'cache_peer_access dify_api allow dst_dify_api path_files\n'
        printf 'cache_peer_access dify_api deny all\n'
        printf 'never_direct allow dst_dify_api path_files\n'
    } >> "$SANDBOX_PROXY_CONF"
fi

expand_env() {
    awk '{
        while(match($0, /\${[A-Za-z_][A-Za-z_0-9]*}/)) {
            var = substr($0, RSTART+2, RLENGTH-3)
            val = ENVIRON[var]
            $0 = substr($0, 1, RSTART-1) val substr($0, RSTART+RLENGTH)
        }
        print
    }' "$1"
}

echo "[ENTRYPOINT] replacing environment variables in the templates"
expand_env /etc/squid/squid.conf.template > /etc/squid/squid.conf
expand_env /etc/squid/dify_common.conf.template > /etc/squid/dify_common.conf

/usr/sbin/squid -Nz
echo "[ENTRYPOINT] starting squid"
/usr/sbin/squid -f /etc/squid/squid.conf -NYC 1
