def file_descriptor(
    size: int, *, media: str = "application/pdf", seed: str = "file", transfer: str = "raw", named: bool = True
) -> dict:
    """Describe one deterministic, bounded fixture File without its bytes."""
    extension = {
        "application/pdf": "pdf",
        "image/png": "png",
        "image/jpeg": "jpg",
        "text/plain": "txt",
        "text/markdown": "md",
    }[media]
    result = {
        "bytes": size,
        "media_type": media,
        "filename": seed + "." + extension,
        "seed": seed,
        "transfer": transfer,
    }
    if named:
        result["name"] = "report"
    return result


def partition(total: int, per_file: int, count: int) -> list[int] | None:
    """Return legal exact-size pieces, or explicitly report an unreachable bound."""
    pieces = (total + per_file - 1) // per_file
    if pieces > count:
        return None
    return [per_file] * max(0, pieces - 1) + ([total - per_file * (pieces - 1)] if pieces else [])


class FileMatrixAcceptance(MatrixAcceptance):
    """Use real uploads, durable Tests, Workflow file grants and peer observations."""

    def upload(self, agent: str, page: str, descriptor: dict, *, expected: tuple[int, ...] = (201,)) -> dict:
        """Upload exact generated bytes; rejected input must not send business work."""
        self.phase = descriptor["seed"]
        before = self.stats()["counts"]["send"]
        content = matrix_file_bytes(descriptor)
        result = self.call(
            "POST",
            f"/external-agents/{agent}/test-files",
            expected=expected,
            data={"page_session_id": page},
            files={"file": (descriptor["filename"], content, descriptor["media_type"])},
        )
        require(self.stats()["counts"]["send"] == before, "Uploading/rejecting an input dispatched business work.")
        if expected == (201,):
            require(
                result.get("size") == len(content) and result.get("lease_id"),
                "Upload did not persist its exact bytes and lease.",
            )
        return result

    def input_test(self, agent: str, page: str, leases: list[str], descriptors: list[dict], case: str) -> None:
        """Send only selected leases and prove exact count/size/hash at the peer."""
        self.phase = case
        before = set(self.stats()["messages"])
        result = self.successful_case(agent, "file-input", page=page, leases=leases, outputs=INPUT_FIELDS)
        require(
            result["outputs"]
            == {
                "text": "file input ok",
                "file_count": len(descriptors),
                "total_bytes": sum(item["bytes"] for item in descriptors),
            },
            "Input boundary bytes or explicit file count changed.",
        )
        self.verify_peer_files(before, descriptors)
        self.report["checks"].append(case)

    def verify_peer_files(self, before: set[str], descriptors: list[dict], *, scenario: str | None = None) -> None:
        """Require one real Send and ordered byte hashes, never URL input transfer."""
        sent = [
            item
            for key, item in self.stats()["messages"].items()
            if key not in before
            and item.get("run") == self.run_id
            and (scenario is None or item.get("scenario") == scenario)
        ]
        require(len(sent) == 1 and sent[0]["sends"] == 1, "A file boundary test replayed or omitted business Send.")
        expected = [
            {
                "size": item["bytes"],
                "sha256": hashlib.sha256(matrix_file_bytes(item)).hexdigest(),
                "media_type": item["media_type"],
            }
            for item in descriptors
        ]
        actual = [{key: item[key] for key in ("size", "sha256", "media_type")} for item in sent[0]["input_files"]]
        require(actual == expected, "The peer did not receive exactly the explicitly referenced file bytes.")
        self.report.setdefault("peer_byte_proofs", []).append({"files": expected, "business_sends": 1})

    def input_boundaries(self, agent: str, limits: dict) -> None:
        """Exercise effective per-file, count and total caps at equality and +1."""
        for kind, media, cap in (
            ("document", "application/pdf", limits["max_document_bytes"]),
            ("image", "image/png", limits["max_image_bytes"]),
        ):
            size = min(cap, limits["max_total_bytes"])
            exact = file_descriptor(size, media=media, seed=f"input-{kind}-exact")
            page = f"matrix-{self.run_id}-{kind}"
            value = self.upload(agent, page, exact)
            self.upload(
                agent,
                f"matrix-{self.run_id}-{kind}-over",
                file_descriptor(cap + 1, media=media, seed=f"input-{kind}-over"),
                expected=(400, 413),
            )
            self.input_test(agent, page, [value["lease_id"]], [exact], f"input_{kind}_exact_and_over")
        self.phase = "input_count_exact_and_over"
        count = limits["max_files"]
        page = f"matrix-{self.run_id}-count"
        descriptors = [file_descriptor(128, media="text/plain", seed=f"input-count-{index}") for index in range(count)]
        uploads = [self.upload(agent, page, item) for item in descriptors]
        self.upload(agent, page, file_descriptor(128, media="text/plain", seed="input-count-over"), expected=(409,))
        detail = self.call("GET", f"/external-agents/{agent}")
        before = self.stats()["counts"]["send"]
        self.call(
            "POST",
            f"/external-agents/{agent}/tests",
            expected=(409,),
            json={
                "page_session_id": page,
                "expected_generation": detail["asset"]["test_display_generation"],
                "idempotency_key": str(uuid4()),
                "task_text": self.text("file-input", "too many references"),
                "input_lease_ids": [item["lease_id"] for item in uploads] + [uploads[0]["lease_id"]],
                "outputs": INPUT_FIELDS,
            },
        )
        require(self.stats()["counts"]["send"] == before, "Too many file references caused Send.")
        self.input_test(agent, page, [item["lease_id"] for item in uploads], descriptors, "input_count_exact_and_over")
        maximum = max(limits["max_document_bytes"], limits["max_image_bytes"])
        media = "application/pdf" if maximum == limits["max_document_bytes"] else "image/png"
        sizes = partition(limits["max_total_bytes"], maximum, count)
        if sizes is None:
            self.report.setdefault("unreachable_boundaries", []).append(
                "total equality is unreachable under stricter per-file/count limits"
            )
        else:
            page = f"matrix-{self.run_id}-total"
            descriptors = [
                file_descriptor(size, media=media, seed=f"input-total-{index}") for index, size in enumerate(sizes)
            ]
            uploads = [self.upload(agent, page, item) for item in descriptors]
            self.upload(agent, page, file_descriptor(1, media="text/plain", seed="input-total-over"), expected=(409,))
            self.input_test(
                agent,
                page,
                [item["lease_id"] for item in uploads],
                descriptors,
                "input_total_exact_and_plus_one_rejected",
            )
        page = f"matrix-{self.run_id}-explicit"
        selected = file_descriptor(128, media="text/markdown", seed="selected")
        ignored = file_descriptor(256, media="text/plain", seed="unreferenced")
        chosen = self.upload(agent, page, selected)
        self.upload(agent, page, ignored)
        self.input_test(agent, page, [chosen["lease_id"]], [selected], "overview_does_not_send_unreferenced_upload")
        self.phase = "jpeg_input_mode_actual_bytes"
        require(
            len(_JPEG) <= limits["max_image_bytes"], "The stricter image profile cannot admit the valid JPEG probe."
        )
        page = f"matrix-{self.run_id}-jpeg"
        uploaded = self.call(
            "POST",
            f"/external-agents/{agent}/test-files",
            expected=(201,),
            data={"page_session_id": page},
            files={"file": ("valid.jpg", _JPEG, "image/jpeg")},
        )
        before = set(self.stats()["messages"])
        result = self.successful_case(
            agent, "file-input", page=page, leases=[uploaded["lease_id"]], outputs=INPUT_FIELDS
        )
        require(
            result["outputs"]["file_count"] == 1 and result["outputs"]["total_bytes"] == len(_JPEG),
            "JPEG bytes were not transmitted exactly.",
        )
        sent = [
            item
            for key, item in self.stats()["messages"].items()
            if key not in before and item.get("run") == self.run_id
        ]
        require(
            len(sent) == 1
            and sent[0]["sends"] == 1
            and sent[0]["input_files"][0]["sha256"] == hashlib.sha256(_JPEG).hexdigest()
            and sent[0]["input_files"][0]["media_type"] == "image/jpeg",
            "The peer did not receive the valid JPEG bytes and MIME.",
        )
        self.report["checks"].append("all_five_input_modes_transmit_actual_bytes")

    def workflow_files(
        self, agent: str, selected: list[dict], descriptors: list[dict], case: str, *, ignored: list[dict] | None = None
    ) -> None:
        """Read stored files through actual Workflow grants and reference only selection."""
        self.phase = case
        app = self.app("workflow")
        value = graph(agent)
        variables = value["nodes"][0]["data"]["variables"]
        for variable in ("selected", "ignored"):
            variables.append(
                {
                    "variable": variable,
                    "label": variable,
                    "type": "file-list",
                    "required": variable == "selected",
                    "allowed_file_types": ["document", "image"],
                    "allowed_file_extensions": [".pdf", ".txt", ".md", ".png", ".jpg"],
                    "allowed_file_upload_methods": ["local_file"],
                    "max_length": 6,
                }
            )
        external = next(item["data"] for item in value["nodes"] if item["id"] == "external")
        external["agent_task"] = "{{#start.task#}}\n{{#start.selected#}}"
        external["agent_declared_outputs"] = [{"name": item["name"], "type": item["kind"]} for item in INPUT_FIELDS]
        value["nodes"][-1]["data"]["outputs"] = [
            {"variable": item["name"], "value_selector": ["external", item["name"]]} for item in INPUT_FIELDS
        ]
        self.save(app, value)
        before = set(self.stats()["messages"])
        self.phase = case
        events = self.stream(
            self.client,
            self.base + f"/apps/{app}/workflows/draft/run",
            {"inputs": {"task": self.text("file-input", case), "selected": selected, "ignored": ignored or []}},
        )
        result = self.wait_terminal(app, self.run_identity(events))
        require(
            result["status"] == "succeeded"
            and result.get("outputs")
            == {
                "text": "file input ok",
                "file_count": len(descriptors),
                "total_bytes": sum(item["bytes"] for item in descriptors),
            },
            "Workflow did not read and transmit its explicit stored Files.",
        )
        self.verify_peer_files(before, descriptors)
        self.report["checks"].append(case)

    def output_files(
        self,
        agent: str,
        case: str,
        descriptors: list[dict],
        *,
        code: str | tuple[str, ...] | None = None,
        fields: list[dict] | None = None,
        artifacts: list[dict] | None = None,
    ) -> None:
        """Materialize valid outputs and verify bytes by real Workflow read-back."""
        self.register(case, files=descriptors, artifacts=artifacts)
        declarations = fields or [{"name": "report", "kind": "array", "item": {"name": "item", "kind": "file"}}]
        if code:
            self.overview(agent, case, declarations, state="failed", code=code)
        else:
            result = self.overview(
                agent, case, declarations, state="succeeded", expected_names={item["name"] for item in declarations}
            )
            files = result["outputs"]["report"]
            files = files if isinstance(files, list) else [files]
            require(len(files) == len(descriptors), "File output mapping changed the file count.")
            require(
                all(
                    item.get("upload_file_id") and item.get("size") == descriptor["bytes"]
                    for item, descriptor in zip(files, descriptors, strict=True)
                ),
                "File output was not durably stored with its exact size.",
            )
            # Overview copies are deliberately private to their exact test lease.
            # A separate real Workflow producer/read-back proves persisted bytes
            # without laundering those temporary Overview files into production.
            self.workflow_output_readback(agent, case, descriptors, declarations)

    def workflow_output_readback(
        self, agent: str, case: str, descriptors: list[dict], declarations: list[dict]
    ) -> None:
        """Materialize and consume Files inside a real, owned Workflow chain."""
        self.phase = case + "_workflow_stored_byte_readback"
        app = self.app("workflow")
        value = graph(agent)
        value["nodes"][0]["data"]["variables"] = []
        producer = next(item["data"] for item in value["nodes"] if item["id"] == "external")
        producer["agent_task"] = f"[byoa:matrix-output:{self.run_id}] {case}"
        producer["agent_declared_outputs"] = [
            {
                "name": item["name"],
                "type": item["kind"],
                **({"array_item": {"type": item["item"]["kind"]}} if "item" in item else {}),
            }
            for item in declarations
        ]
        reader = copy.deepcopy(producer)
        reader["title"] = "Read stored output bytes"
        reader["agent_task"] = f"[byoa:file-input:{self.run_id}] " + "{{#external.report#}}"
        reader["agent_declared_outputs"] = [{"name": item["name"], "type": item["kind"]} for item in INPUT_FIELDS]
        value["nodes"].insert(-1, node("file-reader", reader, 600))
        value["nodes"][-1]["data"]["outputs"] = [
            {"variable": item["name"], "value_selector": ["file-reader", item["name"]]} for item in INPUT_FIELDS
        ]
        ids = ["start", "external", "file-reader", "end"]
        value["edges"] = [
            {
                "id": f"{source}-{target}",
                "type": "custom",
                "source": source,
                "target": target,
                "sourceHandle": "source",
                "targetHandle": "target",
            }
            for source, target in zip(ids, ids[1:], strict=False)
        ]
        self.save(app, value)
        before = set(self.stats()["messages"])
        self.phase = case + "_workflow_stored_byte_readback"
        events = self.stream(self.client, self.base + f"/apps/{app}/workflows/draft/run", {"inputs": {}})
        run = self.run_identity(events)
        result = self.wait_terminal(app, run)
        require(
            result["status"] == "succeeded"
            and result.get("outputs")
            == {
                "text": "file input ok",
                "file_count": len(descriptors),
                "total_bytes": sum(item["bytes"] for item in descriptors),
            },
            "Workflow did not materialize and read back its exact output file bytes.",
        )
        self.verify_peer_files(before, descriptors, scenario="file-input")
        sent = [
            item
            for key, item in self.stats()["messages"].items()
            if key not in before and item.get("run") == self.run_id
        ]
        require(
            len(sent) == 2 and all(item["sends"] == 1 for item in sent),
            "File producer/read-back replayed or skipped a business task.",
        )
        executions = self.call("GET", f"/apps/{app}/workflow-runs/{run}/node-executions")["data"]
        external = [item for item in executions if item.get("node_id") in {"external", "file-reader"}]
        require(
            len(external) == 2 and all(item["status"] == "succeeded" for item in external),
            "The file producer/read-back did not persist both successful node executions.",
        )
        self.report["checks"].append(case + "_workflow_stored_byte_readback")
        self.report.setdefault("workflow_file_proofs", []).append(
            {
                "case": case,
                "app_id": app,
                "run_id": run,
                "node_execution_ids": [item["id"] for item in external],
                "business_sends": 2,
            }
        )

    def output_boundaries(self, agent: str, limits: dict) -> None:
        """Check output raw/URL size/count/total limits and Artifact name mapping."""
        for kind, media, cap in (
            ("document", "application/pdf", limits["max_document_bytes"]),
            ("image", "image/png", limits["max_image_bytes"]),
        ):
            self.output_files(
                agent,
                f"output-{kind}-exact",
                [file_descriptor(min(cap, limits["max_total_bytes"]), media=media, seed=f"output-{kind}-exact")],
            )
            self.output_files(
                agent,
                f"output-{kind}-over",
                [file_descriptor(cap + 1, media=media, seed=f"output-{kind}-over")],
                code="file_too_large",
            )
        count = limits["max_files"]
        self.output_files(
            agent, "output-count-exact", [file_descriptor(128, seed=f"output-count-{index}") for index in range(count)]
        )
        self.output_files(
            agent,
            "output-count-over",
            [file_descriptor(128, seed=f"output-over-{index}") for index in range(count + 1)],
            code="too_many_files",
        )
        maximum = max(limits["max_document_bytes"], limits["max_image_bytes"])
        media = "application/pdf" if maximum == limits["max_document_bytes"] else "image/png"
        for total, case in (
            (limits["max_total_bytes"], "output-total-exact"),
            (limits["max_total_bytes"] + 1, "output-total-over"),
        ):
            sizes = partition(total, maximum, count)
            if sizes is None:
                self.report.setdefault("unreachable_boundaries", []).append(case)
            else:
                descriptors = [
                    file_descriptor(size, media=media, seed=f"{case}-{index}", transfer="url")
                    for index, size in enumerate(sizes)
                ]
                self.output_files(
                    agent,
                    case,
                    descriptors,
                    code=("file_too_large", "file_total_too_large", "file_fetch_failed")
                    if total > limits["max_total_bytes"]
                    else None,
                )
        one = [{"name": "report", "kind": "file"}]
        self.output_files(
            agent,
            "unnamed-file-unique-target",
            [file_descriptor(128, named=False, seed="unnamed-unique", transfer="url")],
            fields=one,
        )
        self.output_files(
            agent,
            "named-file-does-not-fuzzy-match",
            [{**file_descriptor(128, seed="case-sensitive"), "name": "Report"}],
            fields=one,
            code="ambiguous_output",
        )
        self.output_files(
            agent,
            "unnamed-file-multiple-targets",
            [file_descriptor(128, named=False, seed="unnamed-multiple")],
            fields=[*one, {"name": "other", "kind": "file", "required": False}],
            code="ambiguous_output",
        )
        self.output_files(
            agent,
            "structured-and-file-compete",
            [file_descriptor(128, seed="competing")],
            artifacts=[{"artifactId": "structured", "parts": [{"data": {"report": "not a file"}}]}],
            code="ambiguous_output",
        )

    def explicit_workflow(self, agent: str) -> None:
        """An available but unreferenced Workflow file must never reach the peer."""
        descriptors = [
            file_descriptor(128, media="text/plain", seed="workflow-selected"),
            file_descriptor(256, media="text/plain", seed="workflow-ignored"),
        ]
        refs = []
        for item in descriptors:
            uploaded = self.call(
                "POST",
                "/files/upload",
                expected=(201,),
                files={"file": (item["filename"], matrix_file_bytes(item), item["media_type"])},
            )
            refs.append({"type": "document", "transfer_method": "local_file", "upload_file_id": uploaded["id"]})
        self.workflow_files(
            agent, refs[:1], descriptors[:1], "workflow_does_not_send_unreferenced_file", ignored=refs[1:]
        )

    @override
    def run(self) -> dict:
        """Run exact boundaries at effective limits and state any frozen coverage gap."""
        self.login()
        limits = self.call("GET", "/external-agents/capabilities")["limits"]["files"]
        require(
            all(type(limits.get(key)) is int and 0 < limits[key] <= value for key, value in FROZEN.items()),
            "Capabilities exceed the frozen profile or cannot exercise positive file boundaries.",
        )
        stricter = [key for key, value in FROZEN.items() if limits[key] < value]
        if os.environ.get("BYOA_EXPECT_STRICTER_LIMITS") == "1":
            require(stricter, "This run requires a deliberately stricter deployment profile.")
        self.report.update(
            scope="real Overview + Workflow: exact/over file caps, explicit references and stored byte readback",
            effective_file_limits=limits,
            frozen_exact_covered={key: limits[key] == value for key, value in FROZEN.items()},
            stricter_deployment_limits=stricter,
        )
        agent = self.create_asset(bearer=os.environ.get("BYOA_FIXTURE_BEARER"))
        self.input_boundaries(agent, limits)
        self.explicit_workflow(agent)
        self.output_boundaries(agent, limits)
        require(self.stats()["counts"]["input_url"] == 0, "An internal input URL was forwarded instead of bytes.")
        require(self.stats()["counts"]["file_authorization"] == 0, "Agent credentials followed an output file URL.")
        self.report.update(result="passed", finished_at=datetime.now(UTC).isoformat())
        return self.report


def main() -> None:
    """Write sanitized evidence and return failure for any uncovered assertion."""
    runner = FileMatrixAcceptance()
    try:
        result = runner.run()
    except Exception as error:
        result = {
            **runner.report,
            "result": "failed",
            "phase": runner.phase,
            "error": str(error) if isinstance(error, AcceptanceError) else type(error).__name__,
        }
    finally:
        runner.close()
    encoded = json.dumps(result, indent=2)
    if destination := os.environ.get("BYOA_FILE_MATRIX_ACCEPTANCE_OUTPUT"):
        Path(destination).write_text(encoded + "\n")
    print(encoded)
    if result["result"] != "passed":
        raise SystemExit(1)


if __name__ == "__main__":
    main()
