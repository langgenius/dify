def _version(source_plugin_unique_identifier: str) -> Literal["042", "110"]:
    if type(source_plugin_unique_identifier) is str:
        if source_plugin_unique_identifier == OPENAI_CREDIT_LLM_ARTIFACT_SOURCE_UID:
            return "110"
        for version, uid in OPENAI_CREDIT_LLM_SOURCE_UIDS.items():
            if source_plugin_unique_identifier == uid:
                return version
    raise OpenAICreditLLMSourceAdapterError("OpenAI credit LLM source UID is not reviewed")


def openai_credit_llm_protocol(
    *,
    source_plugin_unique_identifier: str,
    source_settings: SourceVariantSettings,
    source_endpoint_class: SourceEndpointClass,
) -> Literal["chat", "responses"]:
    version = _version(source_plugin_unique_identifier)
    selector = getattr(source_settings, "protocol_selector", None)
    base_is_set = getattr(source_settings, "source_base_is_set", None)
    metadata_enabled = getattr(source_settings, "request_metadata_enabled", None)
    if (
        type(source_settings) is not SourceVariantSettings
        or type(selector) is not str
        or selector not in {"absent", "chat", "responses"}
        or type(base_is_set) is not bool
        or type(metadata_enabled) is not bool
        or metadata_enabled is not False
        or type(source_endpoint_class) is not str
        or source_endpoint_class not in {"unset", "official_root"}
        or base_is_set != (source_endpoint_class == "official_root")
    ):
        raise OpenAICreditLLMSourceAdapterError("OpenAI credit LLM source settings are not reviewed")
    if selector == "absent":
        return "chat" if version == "042" else "responses"
    return selector


def validate_openai_credit_llm_identity(
    *,
    source_provider: str,
    source_model: str,
    source_plugin_unique_identifier: str,
    model_type: ModelType,
    target_model: str,
) -> None:
    version = _version(source_plugin_unique_identifier)
    if (
        type(source_provider) is not str
        or source_provider != OPENAI_CREDIT_LLM_SOURCE_PROVIDER
        or type(source_model) is not str
        or source_model not in OPENAI_CREDIT_LLM_SOURCE_MODELS
        or source_model in _UNAVAILABLE[version]
        or model_type is not ModelType.LLM
        or type(target_model) is not str
        or target_model
        != (_REVIEWED042_ALIAS_TARGETS.get(source_model, source_model) if version == "042" else source_model)
    ):
        raise OpenAICreditLLMSourceAdapterError("OpenAI credit LLM source identity is not reviewed")


def _profile_id(
    *,
    source_model: str,
    source_plugin_unique_identifier: str,
    source_settings: SourceVariantSettings,
    source_endpoint_class: SourceEndpointClass,
) -> str:
    version = _version(source_plugin_unique_identifier)
    protocol = openai_credit_llm_protocol(
        source_plugin_unique_identifier=source_plugin_unique_identifier,
        source_settings=source_settings,
        source_endpoint_class=source_endpoint_class,
    )
    endpoint = "official-root" if source_endpoint_class == "official_root" else "unset"
    artifact = "-1ded" if source_plugin_unique_identifier == OPENAI_CREDIT_LLM_ARTIFACT_SOURCE_UID else ""
    return f"openai-credit-{version}{artifact}-{protocol}-{endpoint}-v1:{source_model}"


def _digest_string(value: object) -> TypeGuard[str]:
    return type(value) is str and re.fullmatch(r"sha256:[0-9a-f]{64}", value) is not None


def _schema_digest(schema: AIModelEntity, source_model: str) -> str:
    if (
        not isinstance(schema, AIModelEntity)
        or type(schema.model) is not str
        or schema.model != source_model
        or schema.model_type is not ModelType.LLM
        or not isinstance(schema.model_properties, dict)
        or schema.model_properties.get(ModelPropertyKey.MODE) != "chat"
    ):
        raise OpenAICreditLLMSourceAdapterError("OpenAI credit LLM schema identity is not reviewed")
    try:
        return model_schema_digest(schema)
    except (AttributeError, TypeError, ValueError):
        raise OpenAICreditLLMSourceAdapterError("OpenAI credit LLM schema is not reviewed") from None


def _runtime_pin(
    contract: OpenAICreditLLMSourceContract,
    *,
    expected_source_runtime_schema_digest: str,
    source_runtime_schema: AIModelEntity | None,
) -> None:
    if (
        not _digest_string(expected_source_runtime_schema_digest)
        or not _digest_string(contract.source_runtime_schema_digest)
        or not hmac.compare_digest(expected_source_runtime_schema_digest, contract.source_runtime_schema_digest)
    ):
        raise OpenAICreditLLMSourceAdapterError("OpenAI credit LLM runtime pin does not match")
    # None is prospective construction, not evidence that a runtime was read.
    if source_runtime_schema is not None and not hmac.compare_digest(
        _schema_digest(source_runtime_schema, contract.source_model),
        expected_source_runtime_schema_digest,
    ):
        raise OpenAICreditLLMSourceAdapterError("OpenAI credit LLM runtime schema does not match")


def openai_credit_llm_source_marker(
    contract: OpenAICreditLLMSourceContract,
    *,
    source_provider: str,
    source_model: str,
    model_type: ModelType,
    target_model: str,
) -> dict[str, object]:
    if type(contract) is not OpenAICreditLLMSourceContract or contract not in _ALL_REVIEWED_CONTRACTS:
        raise OpenAICreditLLMSourceAdapterError("Unreviewed frozen OpenAI credit LLM contract")
    validate_openai_credit_llm_identity(
        source_provider=source_provider,
        source_model=source_model,
        source_plugin_unique_identifier=contract.source_plugin_unique_identifier,
        model_type=model_type,
        target_model=target_model,
    )
    if source_model != contract.source_model or target_model != contract.target_model:
        raise OpenAICreditLLMSourceAdapterError("OpenAI credit LLM contract identity does not match")
    return {
        "schema_version": 1,
        "profile_id": contract.profile_id,
        "source_plugin_uid": contract.source_plugin_unique_identifier,
        "source_model": contract.source_model,
        "source_schema_digest": contract.source_schema_digest,
        "rules_digest": contract.rules_digest,
    }


def build_openai_credit_llm_source_contract(
    *,
    adapter_id: str,
    adapter_revision: str,
    expected_rules_digest: str,
    source_provider: str,
    source_model: str,
    source_plugin_unique_identifier: str,
    source_schema: AIModelEntity,
    expected_source_schema_digest: str,
    expected_source_runtime_schema_digest: str,
    target_model: str,
    source_settings: SourceVariantSettings,
    source_endpoint_class: SourceEndpointClass,
    source_runtime_schema: AIModelEntity | None = None,
) -> OpenAICreditLLMSourceContract:
    openai_credit_llm_protocol(
        source_plugin_unique_identifier=source_plugin_unique_identifier,
        source_settings=source_settings,
        source_endpoint_class=source_endpoint_class,
    )
    actual_catalog_digest = _schema_digest(source_schema, source_model)
    validate_openai_credit_llm_identity(
        source_provider=source_provider,
        source_model=source_model,
        source_plugin_unique_identifier=source_plugin_unique_identifier,
        model_type=source_schema.model_type,
        target_model=target_model,
    )
    profile_id = _profile_id(
        source_model=source_model,
        source_plugin_unique_identifier=source_plugin_unique_identifier,
        source_settings=source_settings,
        source_endpoint_class=source_endpoint_class,
    )
    contract = next(
        (
            c
            for c in _ALL_REVIEWED_CONTRACTS
            if c.profile_id == profile_id and c.source_plugin_unique_identifier == source_plugin_unique_identifier
        ),
        None,
    )
    if (
        contract is None
        or type(adapter_id) is not str
        or adapter_id != OPENAI_CREDIT_LLM_SOURCE_ADAPTER_ID
        or type(adapter_revision) is not str
        or adapter_revision != OPENAI_CREDIT_LLM_SOURCE_ADAPTER_REVISION
        or contract.adapter_id != adapter_id
        or contract.algorithm_revision != adapter_revision
        or contract.source_plugin_unique_identifier != source_plugin_unique_identifier
        or not _digest_string(expected_source_schema_digest)
        or not _digest_string(expected_rules_digest)
        or not hmac.compare_digest(actual_catalog_digest, expected_source_schema_digest)
        or not hmac.compare_digest(actual_catalog_digest, contract.source_schema_digest)
        or not hmac.compare_digest(expected_rules_digest, contract.rules_digest)
    ):
        raise OpenAICreditLLMSourceAdapterError("OpenAI credit LLM source evidence does not match")
    _runtime_pin(
        contract,
        expected_source_runtime_schema_digest=expected_source_runtime_schema_digest,
        source_runtime_schema=source_runtime_schema,
    )
    openai_credit_llm_source_marker(
        contract,
        source_provider=source_provider,
        source_model=source_model,
        model_type=source_schema.model_type,
        target_model=target_model,
    )
    return contract


def restore_openai_credit_llm_source_contract(
    marker: object,
    *,
    source_provider: str,
    source_model: str,
    model_type: ModelType,
    target_model: str,
    source_settings: SourceVariantSettings,
    source_endpoint_class: SourceEndpointClass,
    expected_source_runtime_schema_digest: str,
    source_runtime_schema: AIModelEntity | None = None,
) -> OpenAICreditLLMSourceContract:
    fields = {
        "schema_version",
        "profile_id",
        "source_plugin_uid",
        "source_model",
        "source_schema_digest",
        "rules_digest",
    }
    if (
        type(marker) is not dict
        or set(marker) != fields
        or type(marker["schema_version"]) is not int
        or marker["schema_version"] != 1
        or any(type(value) is not str for key, value in marker.items() if key != "schema_version")
    ):
        raise OpenAICreditLLMSourceAdapterError("Invalid frozen OpenAI credit LLM marker")
    profile_id = _profile_id(
        source_model=source_model,
        source_plugin_unique_identifier=marker["source_plugin_uid"],
        source_settings=source_settings,
        source_endpoint_class=source_endpoint_class,
    )
    contract = next(
        (
            c
            for c in _ALL_REVIEWED_CONTRACTS
            if c.profile_id == profile_id and c.source_plugin_unique_identifier == marker["source_plugin_uid"]
        ),
        None,
    )
    if contract is None:
        raise OpenAICreditLLMSourceAdapterError("Invalid frozen OpenAI credit LLM marker")
    expected = openai_credit_llm_source_marker(
        contract,
        source_provider=source_provider,
        source_model=source_model,
        model_type=model_type,
        target_model=target_model,
    )
    if (
        not _digest_string(marker["rules_digest"])
        or not _digest_string(marker["source_schema_digest"])
        or not hmac.compare_digest(marker["rules_digest"], contract.rules_digest)
        or not hmac.compare_digest(marker["source_schema_digest"], contract.source_schema_digest)
        or any(marker[key] != expected[key] for key in fields - {"rules_digest", "source_schema_digest"})
    ):
        raise OpenAICreditLLMSourceAdapterError("Invalid frozen OpenAI credit LLM marker")
    _runtime_pin(
        contract,
        expected_source_runtime_schema_digest=expected_source_runtime_schema_digest,
        source_runtime_schema=source_runtime_schema,
    )
    return contract
